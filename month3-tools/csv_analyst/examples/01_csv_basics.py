"""
01_csv_basics.py - pandas 基础探索

只用 5 个 pandas 函数,就能搞定 80% 数据探查任务:
- pd.read_csv()
- df.head()
- df.shape
- df.info()
- df.describe()
"""

import pandas as pd
# ============================================================
# 1. 读 CSV
# ============================================================

df = pd.read_csv('data/sales.csv')
print("=" * 60)
print("✅ CSV 加载成功")
print("=" * 60)

# ============================================================
# 2. 查看前几行(类似 Linux 的 head 命令)
# ============================================================

print("\n>>> df.head(5) —— 前 5 行:")
print(df.head(5))

# ============================================================
# 3. 查看维度(行数, 列数)
# ============================================================


print(f"\n>>> df.shape: {df.shape}")
print(f"   行数：{df.shape[0]}")
print(f"   列数：{df.shape[1]}")

# ============================================================
# 4. 查看列名 + 数据类型
# ============================================================

print("\n>>> df.dtype -- 每列数据类型：")
print(df.dtypes)

print("\n>>> df.columns.tolist() -- 列名列表：")
print(df.columns.tolist())

# ============================================================
# 5. 描述性统计(神级方法!)
# ============================================================

print("\n>>> df.describe() -- 数值列统计：")
print(df.describe())

# ============================================================
# 6. 简单的列查询
# ============================================================
print("\n>>> 单列查询:sales_amount 列前 5 个值:")
print(df['sales_amount'].head(5))

print(f"\n>>> sales_amount 总和:{df['sales_amount'].sum():,}")
print(f">>> sales_amount 均值:{df['sales_amount'].mean():,.0f}")
print(f">>>sales_amount 最大:{df['sales_amount'].max():,}")